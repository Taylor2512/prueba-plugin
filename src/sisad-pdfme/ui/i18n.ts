/**
 * Idiomas con diccionario completo disponible.
 */
export const SUPPORTED_LANGS = Object.keys(dictionaries) as Lang[];

/**
 * Resuelve un idioma posiblemente inválido al contrato `Lang`.
 *
 * Es el ÚNICO punto autorizado para aplicar el fallback de idioma: cualquier
 * capa que reciba un locale del host (config declarativa, `UIOptions.lang`,
 * snapshots restaurados) debe pasar por aquí en lugar de declarar su propio
 * `?? 'en'` / `|| 'es'`. Un idioma no resoluble cae en `DEFAULT_LANG`.
 */
export const resolveLang = (candidate: unknown): Lang => {
  const parsed = LangSchema.safeParse(candidate);
  return parsed.success ? parsed.data : DEFAULT_LANG;
};

/**
 * Devuelve el diccionario completo del idioma indicado.
 *
 * No mezcla idiomas: un `Dict` incompleto produciría interfaces bilingües, así
 * que cada diccionario debe cumplir el contrato entero y el fallback es el
 * diccionario de `DEFAULT_LANG` completo.
 */
export const getDict = (lang: Lang): Dict => dictionaries[lang] || dictionaries[DEFAULT_LANG];

export const i18n = (key: keyof Dict, dict?: Dict) => (dict || getDict(DEFAULT_LANG))[key];

/** Función de traducción tal como la publica `I18nContext`. */
export type Translate = (key: keyof Dict) => string;

/**
 * Traducción para código que no puede alcanzar `I18nContext`.
 *
 * Resuelve contra `DEFAULT_LANG` y por tanto ignora `options.lang`/`options.labels`:
 * úsala sólo en helpers públicos llamados desde fuera del árbol React. Dentro de
 * componentes, consume siempre `I18nContext`.
 */
export const defaultTranslate: Translate = (key) => i18n(key);

/**
 * Resuelve la etiqueta visible de un `schema.type`.
 *
 * Contrato: `type` es identidad técnica estable y NUNCA se traduce ni se
 * reescribe; esta función sólo elige su presentación. Para plugins del host que
 * no tienen key en `Dict` se conserva la etiqueta aportada por el plugin, y sólo
 * si tampoco existe se muestra el `type` como último recurso, para no exponer
 * `undefined`.
 */
export const resolveSchemaTypeLabel = (
  translate: Translate,
  type: string,
  fallbackLabel?: string,
): string => {
  const normalizedType = String(type || '').trim();
  const key = `schemaTypes.${normalizedType}` as keyof Dict;
  if (normalizedType && key in dictionaries[DEFAULT_LANG]) {
    const translated = String(translate(key) || '').trim();
    if (translated) return translated;
  }
  const fallback = String(fallbackLabel || '').trim();
  return fallback || normalizedType;
};

/**
 * Resuelve la etiqueta visible de una categoría del catálogo.
 *
 * La category key sigue siendo el identificador de agrupación y orden; las
 * categorías aportadas por el host que no tengan key en `Dict` se muestran tal
 * cual las declaró el host.
 */
export const resolveSchemaCategoryLabel = (translate: Translate, category: string): string => {
  const normalizedCategory = String(category || '').trim();
  const key = `schemaCategories.${normalizedCategory}` as keyof Dict;
  if (normalizedCategory && key in dictionaries[DEFAULT_LANG]) {
    const translated = String(translate(key) || '').trim();
    if (translated) return translated;
  }
  return normalizedCategory;
};
